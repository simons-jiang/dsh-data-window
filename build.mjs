/**
 * Assemble `client.js` from the readable fragments in `src/client`.
 *
 * The browser module loader takes ONE file per package id, so the fragments are
 * concatenated into a single factory body inside the loader envelope. Locale
 * dictionaries are inlined from `locale/*.json` — the same files the Plugin
 * Manager reads for the display title — so the UI copy has one source of truth.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const pkg = JSON.parse(await readFile(join(here, 'package.json'), 'utf8'))
const sourceDir = join(here, 'src', 'client')
const files = (await readdir(sourceDir)).filter((name) => name.endsWith('.js')).sort()

/** The dictionary the factory carries, without the display metadata. */
async function dictionary(locale) {
  const document = JSON.parse(await readFile(join(here, 'locale', `${locale}.json`), 'utf8'))
  const entries = Object.entries(document).filter(([key]) => key !== 'meta')
  const body = entries
    .map(([key, value]) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
    .join('\n')
  return `  const DW_TEXT_${locale.toUpperCase()} = {\n${body}\n  }`
}

/**
 * Drop module syntax from a fragment.
 *
 * The fragments are readable as ES modules (so `node --check` and an editor both
 * understand them), but they are concatenated into ONE factory body, where an
 * `export` statement is a syntax error.
 */
function stripExports(text) {
  return text
    .replace(/^\s*export\s*\{[^}]*\}\s*$/gm, '')
    .replace(/(^|\n)(\s*)export\s+(default\s+)?(async\s+)?(function|class|const|let|var)\b/g, (match, lead, indent, isDefault, isAsync, keyword) => `${lead}${indent}${isAsync ?? ''}${keyword}`)
}

const fragments = []
for (const name of files) {
  const text = await readFile(join(sourceDir, name), 'utf8')
  fragments.push(`// ---- ${name} ${'-'.repeat(Math.max(0, 68 - name.length))}\n${stripExports(text.trim())}\n`)
}

const envelope = `/**
 * dsh-data-window — Client half. Generated by build.mjs from src/client/*.js;
 * edit those sources, then run \`node build.mjs\`.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const React = require('react')
    const { useCallback, useEffect, useMemo, useRef, useState, useSyncExternalStore } = React
    const h = React.createElement
${await dictionary('en')}
${await dictionary('zh')}

${fragments.join('\n')}
    // The client runtime refuses any service that is not declared here.
    return { inject: ['slots', 'locale'], apply }
  },
})
`

/**
 * Fail the build when a fragment calls a helper that no fragment defines.
 *
 * The loader would only discover this at the moment a user clicks, which is the
 * worst possible time; a text-level check turns it into a build error here.
 */
function undeclaredHelpers(body) {
  const declared = new Set()
  for (const match of body.matchAll(/(?:^|\n)\s*(?:async\s+)?function\s+([A-Za-z_$][\w$]*)/g)) declared.add(match[1])
  for (const match of body.matchAll(/(?:^|\n)\s*(?:const|let|var|class)\s+([A-Za-z_$][\w$]*)/g)) declared.add(match[1])
  // React bindings and module-level constants come from the envelope.
  for (const name of ['React', 'h', 'useCallback', 'useEffect', 'useMemo', 'useRef', 'useState', 'useSyncExternalStore', 'require', 'apply']) {
    declared.add(name)
  }
  const missing = new Set()
  for (const match of body.matchAll(/\b((?:dw|Dw)[A-Z][\w$]*)\s*(?=[(.,\[])/g)) {
    const name = match[1]
    if (declared.has(name)) continue
    const before = body.slice(Math.max(0, match.index - 2), match.index)
    if (before === '.') continue
    missing.add(name)
  }
  return [...missing].sort()
}

const missing = undeclaredHelpers(envelope)
if (missing.length > 0) {
  console.error(`client.js: ${missing.length} helper(s) are referenced but never defined:\n  ${missing.join('\n  ')}`)
  process.exitCode = 1
  throw new Error(`undeclared helpers: ${missing.join(', ')}`)
}

await writeFile(join(here, 'client.js'), envelope, 'utf8')
console.log(`client.js: ${files.length} fragments, ${envelope.length} bytes`)
